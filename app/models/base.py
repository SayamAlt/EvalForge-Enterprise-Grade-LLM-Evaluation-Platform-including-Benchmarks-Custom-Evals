"""
SQLAlchemy declarative base with shared audit columns.

CONCEPT: ORM Models vs Pydantic Schemas
──────────────────────────────────────────
Two separate class hierarchies serve two different purposes:

  app/models/   → SQLAlchemy ORM models
    - Define the database TABLE structure
    - Hold relationships (foreign keys, joins)
    - Used only inside services/repositories
    - Never returned directly from API endpoints

  app/schemas/  → Pydantic models
    - Define the API REQUEST/RESPONSE shape
    - Used for serialization/validation at the HTTP boundary
    - Decoupled from the DB schema (can expose different fields)

Example: DatasetORM has a `raw_data` JSON column you never expose in the API.
DatasetRead (Pydantic) only includes the fields the client needs.

Every ORM model gets these audit columns automatically via Base:
    id         UUID primary key (generated by default)
    created_at Timestamp set on INSERT
    updated_at Timestamp updated on every UPDATE
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Abstract base for all EvalForge ORM models."""

    __abstract__ = True

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
